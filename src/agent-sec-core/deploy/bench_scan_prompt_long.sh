# 需要毫秒级墙上时间。优先用 date +%s.%N；macOS 自带 date 无 %N，
# 退化到秒级会不够精确，这里用 python 兜底(若可用)取高精度时间。
now_ns() {
  local t
  t=$(date +%s%N 2>/dev/null)
  if [ "${#t}" -ge 12 ] && [[ "$t" != *N* ]]; then
    echo "$t"
  else
    # macOS/BSD date 不支持 %N，用 python 兜底
    python3 -c 'import time;print(int(time.perf_counter()*1e9))' 2>/dev/null \
      || python -c 'import time;print(int(time.time()*1e9))' 2>/dev/null \
      || echo "$(( $(date +%s) * 1000000000 ))"
  fi
}

total=${#TEXTS[@]}
