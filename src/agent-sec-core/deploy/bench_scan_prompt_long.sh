echo "文本条数   : ${total}   预热(丢弃)前 ${WARMUP} 次"
echo "--------------------------------------------------------"

sum=0            # 计入统计的耗时之和(纳秒)
count=0          # 计入统计的次数
fail=0
min_ns=""
max_ns=0

i=0
for text in "${TEXTS[@]}"; do
  start=$(now_ns)
  # shellcheck disable=SC2086
  $CLI scan-prompt --text "$text" --mode "$MODE" >/dev/null 2>&1
  rc=$?
  end=$(now_ns)

  elapsed=$(( end - start ))            # 纳秒
  ms=$(( elapsed / 1000000 ))           # 整数毫秒(仅显示)

  if [ "$i" -lt "$WARMUP" ]; then
    tag="预热丢弃"
  else
    tag="计入统计"
  fi
  status=""
  [ "$rc" -ne 0 ] && status="  [!! 失败 rc=$rc]" && fail=$(( fail + 1 ))

  preview=$(printf '%s' "$text" | cut -c1-16)
  printf '[%2d/%d] %7d ms  %s  %s…%s\n' "$((i+1))" "$total" "$ms" "$tag" "$preview" "$status"

  if [ "$i" -ge "$WARMUP" ] && [ "$rc" -eq 0 ]; then
    sum=$(( sum + elapsed ))
    count=$(( count + 1 ))
    if [ -z "$min_ns" ] || [ "$elapsed" -lt "$min_ns" ]; then min_ns=$elapsed; fi
    if [ "$elapsed" -gt "$max_ns" ]; then max_ns=$elapsed; fi
  fi
  i=$(( i + 1 ))
done

echo "--------------------------------------------------------"
if [ "$count" -eq 0 ]; then
  echo "没有可用于统计的成功调用。"
  exit 1
fi

avg_ns=$(( sum / count ))
# 转成带一位小数的毫秒
avg_ms=$(awk "BEGIN{printf \"%.1f\", $avg_ns/1000000}")
min_ms=$(awk "BEGIN{printf \"%.1f\", $min_ns/1000000}")
max_ms=$(awk "BEGIN{printf \"%.1f\", $max_ns/1000000}")

echo "计入统计次数 : ${count}"
[ "$fail" -ne 0 ] && echo "失败次数     : ${fail}"
echo "平均耗时     : ${avg_ms} ms"
echo "最小 / 最大  : ${min_ms} ms / ${max_ms} ms"
